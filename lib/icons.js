// 把图标原语转成场景条目（scene items），供 SVG / PPTX 复用
export function iconItems(id, cx, cy, size, { stroke = '#1E63E9', sw = 1.4 } = {}) {
  const def = ICONS[id];
  if (!def) return [];
  const s = size / 24;
  const X = (x) => cx - size / 2 + x * s;
  const Y = (y) => cy - size / 2 + y * s;
  const items = [];
  const arcPts = (cxp, cyp, r, a0, a1) => {
    const pts = [];
    const n = Math.max(6, Math.round(Math.abs(a1 - a0) / 8));
    for (let i = 0; i <= n; i++) {
      const a = ((a0 + (a1 - a0) * i / n) * Math.PI) / 180;
      pts.push([X(cxp + Math.cos(a) * r), Y(cyp + Math.sin(a) * r)]);
    }
    return pts;
  };
  for (const [kind, v] of def.g) {
    if (kind === 'L') items.push({ type: 'line', x1: X(v[0]), y1: Y(v[1]), x2: X(v[2]), y2: Y(v[3]), stroke, sw });
    else if (kind === 'C') items.push({ type: 'ellipse', x: X(v[0]) - v[2] * s, y: Y(v[1]) - v[2] * s, w: v[2] * s * 2, h: v[2] * s * 2, stroke, sw, fill: 'none' });
    else if (kind === 'P') items.push({ type: 'poly', open: v[0] === 1, points: v[1].map((p) => [X(p[0]), Y(p[1])]), stroke, sw, fill: 'none' });
    else if (kind === 'A') items.push({ type: 'poly', open: true, points: arcPts(v[0], v[1], v[2], v[3], v[4]), stroke, sw, fill: 'none' });
  }
  return items;
}

export function hasIcon(label) { return !!iconForLabel(label); }
export function iconForLabel(label) {
  if (!label) return null;
  const t = String(label);
  if (LABEL_ICON[t]) return LABEL_ICON[t];
  // 模糊匹配：取命中键里最长的一个，避免「数据资产」误判成「数据」
  let best = null;
  for (const k of Object.keys(LABEL_ICON)) {
    if (t.includes(k) && (!best || k.length > best.length)) best = k;
  }
  return best ? LABEL_ICON[best] : null;
}
